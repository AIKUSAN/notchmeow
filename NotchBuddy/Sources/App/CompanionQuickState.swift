import Foundation

// The quick actions' pure state (F3a-mac, Task 8): where a quick action's text comes from, the cap on a huge clipboard, the result card's states, the
// "latest run wins" gate, and the one turn a quick Explain answers under its own system text. No pasteboard, no app, no clock: the caller passes the
// values in. The text is data (CompanionQuick wraps it in <text> tags before it reaches a model); nothing here keeps or logs it.
// Replayed by scripts/test-companion-quick.sh.

enum CompanionQuickRules {
    /// What the card says when the model's reply holds no text once it is cleaned.
    static let emptyNote = "Nothing came back. Try again."
    /// What the chat says when "Explain the copied screenshot" finds no image it can read (gone from the clipboard, too big, not an image).
    static let noImageNote = "I couldn't read an image on the clipboard."
    /// What Services shows (the OS's own alert) when a quick action is started with nothing selected.
    static let noSelectionNote = "Select some text first."
    /// The grey line on a card whose text came from the clipboard (not from the field, not from another app's selection).
    static let clipboardNote = "From the clipboard."

    /// Whether a chat note is the "Select some text first." one an empty menu action left: a quick action that starts clears only that one, never another note.
    static func clearsNotice(_ text: String?) -> Bool { text == noSelectionNote }
}

/// Where a quick action's text comes from when it is started from the chat's menu.
enum CompanionQuickSource {
    /// The most characters of a clipboard text a quick action reads. CompanionQuick sends only the first 8,000 code points, so more is never needed;
    /// this bound only keeps a clipboard of tens of megabytes from being scanned on the main actor.
    static let capChars = 60_000

    /// The pasteboard types nspasteboard.org defines for a copy that must not be read: a password manager's secret, a transient copy, an auto-generated one.
    /// Raw names, so a test can pass a fake type list.
    static let skippedTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// Whether a pasteboard's type list carries any of the skipped types.
    static func hasSkippedType(_ types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// The UTIs of the images "Explain the copied screenshot" can read (PNG, TIFF). Raw names, as `skippedTypes`.
    static let imageTypes = ["public.png", "public.tiff"]

    /// Whether the clipboard's type list offers an image and carries no skipped type. The screenshot is read, and its menu item offered, only then: the decision
    /// is made on the type names, before any data is read.
    static func holdsReadableImage(_ types: [String]) -> Bool {
        !hasSkippedType(types) && types.contains { imageTypes.contains($0) }
    }

    /// The field's text when it holds words, else the clipboard's string when it holds words and carries no skipped type; nil when neither does. The field is
    /// kept as typed, and only the clipboard's text is labelled `fromClipboard`.
    static func pick(field: String, pasteboard: String?, pasteboardTypes: [String]) -> (text: String, fromClipboard: Bool)? {
        if hasWords(field) { return (field, false) }
        if !hasSkippedType(pasteboardTypes), let pasteboard, hasWords(pasteboard) { return (pasteboard, true) }
        return nil
    }

    /// The text cut to `capChars` characters (a character is never split), and whether anything was cut.
    static func capped(_ text: String) -> (text: String, cut: Bool) {
        // The UTF-8 length is O(1) for a Swift string; a text that cannot reach the cap is not counted at all.
        guard text.utf8.count > capChars else { return (text, false) }
        let head = text.prefix(capChars)
        return (String(head), head.endIndex != text.endIndex)
    }

    private static func hasWords(_ s: String) -> Bool {
        s.contains { !$0.isWhitespace }
    }
}

/// The card above the chat's field while a Fix or Rewrite runs, and after it.
struct QuickResult: Equatable {
    let kind: String
    var text: String
    var running: Bool
    var cut: Bool
    var note: String?
    /// The app the selection came from (Services only); Replace is offered only with one.
    let sourcePID: pid_t?
    /// The text came from the clipboard (the chat's menu, with no field words): the card says so.
    var fromClipboard = false

    static func started(kind: String, cut: Bool, sourcePID: pid_t?, fromClipboard: Bool = false) -> QuickResult {
        QuickResult(kind: kind, text: "", running: true, cut: cut, note: nil, sourcePID: sourcePID, fromClipboard: fromClipboard)
    }

    /// The cleaned reply. A reply with no text is a failure with a fixed sentence.
    func finished(text: String) -> QuickResult {
        guard !text.isEmpty else { return failed(CompanionQuickRules.emptyNote) }
        var r = self
        r.text = text
        r.running = false
        r.note = nil
        return r
    }

    func failed(_ note: String) -> QuickResult {
        var r = self
        r.text = ""
        r.running = false
        r.note = note
        return r
    }

    var title: String { kind == "rewrite" ? "Rewritten" : "Fixed" }
    /// The card's heading: the title once there is a result, "Fixing…" or "Rewriting…" while it runs, and a plain "Couldn't fix that" after a failure.
    var heading: String {
        let rewrite = kind == "rewrite"
        if running { return rewrite ? "Rewriting…" : "Fixing…" }
        return text.isEmpty ? (rewrite ? "Couldn't rewrite that" : "Couldn't fix that") : title
    }
    var canCopy: Bool { !running && !text.isEmpty }
    /// Replace needs the app to go back to (a quick action started from the chat's own menu has none), and a whole text: a result made from a cut text
    /// would paste over the part of the selection that was never sent.
    var canReplace: Bool { canCopy && sourcePID != nil && !cut }
}

/// Only the latest quick run may write the card: a run that was overtaken (or whose card was closed) lands late and is dropped.
struct QuickGate {
    private(set) var current = 0

    mutating func begin() -> Int {
        current += 1
        return current
    }

    func isCurrent(_ run: Int) -> Bool { run == current }

    /// The card was closed: every run in flight is stale.
    mutating func invalidate() { current += 1 }
}

/// A quick Explain's first turn: the question and the system text it is answered under. The system text applies to that one question, asked as the
/// chat's first message; once its reply has landed, or for any other question, the turn is a normal companion turn.
struct QuickFirstTurn: Equatable {
    let system: String
    let user: String

    /// `turnCount` is the model's turns so far, before this question is added: 0 for a first try, 1 when the question is already in (a retry after
    /// the user turn stayed), 2 or more once a reply has landed.
    func system(forQuery query: String, turnCount: Int) -> String? {
        query == user && turnCount <= 1 ? system : nil
    }
}
