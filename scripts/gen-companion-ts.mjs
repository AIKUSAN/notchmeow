#!/usr/bin/env node
// Writes the TypeScript copy of the Companion rules from shared/companion-core.js (sub-project F3a, docs/COMPANION-CONTRACT.md):
//   windows/src/companion/core.generated.ts   (Windows and Linux)
// The rules are written once. The Windows and Linux app does not carry a second, hand-made port of them: it carries this generated copy, so the two cannot drift,
// and `npm run check:companion` replays every fixture of tests/fixtures/companion/ against it, in the app's own language.
//   node scripts/gen-companion-ts.mjs            write it
//   node scripts/gen-companion-ts.mjs --check    write nothing; exit 1 if the file differs from what would be written (CI)
// Node standard library only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = path.join(ROOT, 'shared/companion-core.js');
export const OUTPUT = path.join(ROOT, 'windows/src/companion/core.generated.ts');

const HEAD = [
  '// GENERATED by scripts/gen-companion-ts.mjs from shared/companion-core.js. Do not edit: change the source and run `node scripts/gen-companion-ts.mjs`.',
  "// The source is a UMD file; here it runs as an ES module, with a `module` of its own to export through. The typed names are in core.ts.",
  '// @ts-nocheck',
  'const module: { exports: any } = { exports: {} };',
].join('\n');

/** The text of the generated file for a given source text. */
export function render(source) {
  return `${HEAD}\n${source.replace(/\s+$/, '')}\nexport const CompanionCore = module.exports;\n`;
}

function main() {
  const want = render(fs.readFileSync(SOURCE, 'utf8'));
  const have = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (have === want) { console.log('✓ windows/src/companion/core.generated.ts matches shared/companion-core.js'); return; }
    console.error('✗ windows/src/companion/core.generated.ts is stale: run `node scripts/gen-companion-ts.mjs`');
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  if (have !== want) fs.writeFileSync(OUTPUT, want);
  console.log(`${have === want ? 'unchanged' : 'wrote'} windows/src/companion/core.generated.ts`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
