import Foundation

// The music pill's rules (MusicFollow): the two apps, the player states, the track clean-up, which app is shown, the scripts and the words.
// Run it through scripts/test-music-follow.sh.

@main
enum MusicFollowTests {
    @MainActor static func main() {
        CT.section("the two apps")
        CT.check("order", MusicApp.allCases, [.appleMusic, .spotify])
        CT.check("bundle IDs", MusicApp.allCases.map(\.bundleId), ["com.apple.Music", "com.spotify.client"])
        CT.check("notifications", MusicApp.allCases.map(\.notificationName), ["com.apple.Music.playerInfo", "com.spotify.client.PlaybackStateChanged"])
        CT.check("labels", MusicApp.allCases.map(\.label), ["Apple Music", "Spotify"])
        CT.check("grant flags: Apple Music keeps today's", MusicApp.allCases.map(\.grantedKey), ["notchmeow.musicAutomationGranted", "notchmeow.spotifyAutomationGranted"])
        CT.check("of(bundleId:) is exact", [MusicApp.of(bundleId: "com.spotify.client"), MusicApp.of(bundleId: "com.apple.Music"), MusicApp.of(bundleId: "com.apple.music"), MusicApp.of(bundleId: nil)], [.spotify, .appleMusic, nil, nil])

        CT.section("player states")
        CT.check("notification words", ["Playing", "Paused", "Stopped", "playing", "Buffering", ""].map { MusicPlayback.fromNotification($0) }, [.playing, .paused, .stopped, nil, nil, nil])
        CT.check("no state", MusicPlayback.fromNotification(nil), nil)
        CT.check("script words", ["playing", "paused", "stopped", "fast forwarding", "rewinding", "kPSP", ""].map { MusicPlayback.fromScript($0) }, [.playing, .paused, .stopped, .playing, .playing, nil, nil])

        CT.section("the track, cleaned as today")
        let t = MusicTrack(name: "Song (Remastered 2011) [Live] - Radio Edit", artist: "Ana feat. Bo", album: "")
        CT.check("title", t.title, "Song")
        CT.check("artist", t.artist, "Ana")
        CT.check("blank album", t.album, nil)
        CT.check("a title that is only brackets stays", MusicTrack(name: "(Intro)", artist: nil, album: nil).title, "(Intro)")
        CT.check("ft.", MusicTrack(name: "x", artist: "Ana ft. Bo", album: nil).artist, "Ana")
        CT.check("blank and missing", [MusicTrack(name: nil, artist: "  ", album: nil).title, MusicTrack(name: nil, artist: "  ", album: nil).artist], [nil, nil])

        CT.section("which app is shown")
        let a = MusicTrack(name: "A", artist: "Ann", album: nil)
        let s = MusicTrack(name: "S", artist: "Sam", album: nil)
        var f = MusicFollow()
        CT.check("nothing yet", f.shown, nil)
        CT.checkTrue("not playing", !f.isPlaying)
        f.apply(.appleMusic, .playing, a)
        CT.check("Apple Music plays", f.shown, .appleMusic)
        f.apply(.spotify, .paused, s)
        CT.check("a paused Spotify does not take over a playing Apple Music", f.shown, .appleMusic)
        f.apply(.spotify, .playing, s)
        CT.check("both play: the latest play wins", f.shown, .spotify)
        CT.check("its track", f.shownTrack, s)
        f.apply(.appleMusic, .playing, MusicTrack(name: "A2", artist: nil, album: nil))
        CT.check("a track change is a newer play", f.shown, .appleMusic)
        f.apply(.appleMusic, .paused, a)
        CT.check("the shown one pauses while the other plays: the other shows", f.shown, .spotify)
        CT.checkTrue("still playing", f.isPlaying)
        f.apply(.spotify, .paused, s)
        CT.check("both paused: the latest pause wins", f.shown, .spotify)
        CT.checkTrue("nothing plays", !f.isPlaying)
        f.apply(.spotify, .stopped, s)
        CT.check("Spotify stops: the paused Apple Music shows, with its last track", [f.shown?.rawValue, f.shownTrack?.title], ["appleMusic", "A"])
        f.remove(.appleMusic)
        CT.check("Apple Music quits: nothing", f.shown, nil)
        CT.check("no track", f.shownTrack, nil)
        f.apply(.spotify, .playing, s)
        f.clear()
        CT.check("clear forgets both", f.entries.count, 0)
        var g = MusicFollow()
        g.apply(.spotify, .stopped, s)
        CT.check("a stop from an app never seen changes nothing", g.entries.count, 0)

        CT.section("the scripts: only to a running app")
        CT.check("Apple Music play/pause", MusicFollow.script(.playPause, for: .appleMusic), "if application id \"com.apple.Music\" is running then\n    tell application id \"com.apple.Music\" to playpause\nend if")
        CT.check("Spotify previous", MusicFollow.script(.previous, for: .spotify), "if application id \"com.spotify.client\" is running then\n    tell application id \"com.spotify.client\" to previous track\nend if")
        CT.check("Apple Music previous is today's back track", MusicFollow.script(.previous, for: .appleMusic), "if application id \"com.apple.Music\" is running then\n    tell application id \"com.apple.Music\" to back track\nend if")
        CT.check("Apple Music next", MusicFollow.script(.next, for: .appleMusic), "if application id \"com.apple.Music\" is running then\n    tell application id \"com.apple.Music\" to next track\nend if")
        CT.check("Spotify next", MusicFollow.script(.next, for: .spotify), "if application id \"com.spotify.client\" is running then\n    tell application id \"com.spotify.client\" to next track\nend if")
        CT.check("the Automation denial code", MusicFollow.deniedCode, -1743)
        for app in MusicApp.allCases {
            let r = MusicFollow.readScript(for: app)
            CT.checkTrue("\(app.label): the read checks first", r.hasPrefix("if application id \"\(app.bundleId)\" is not running then return {\"stopped\", \"\", \"\", \"\"}\ntell application id \"\(app.bundleId)\"\n"))
            CT.checkTrue("\(app.label): state, name, artist, album", r.contains("set ps to player state as string") && r.contains("return {ps, n, ar, al}") && r.hasSuffix("end tell"))
        }

        CT.section("the words")
        CT.check("playing", MusicFollow.statusLine(shown: .spotify, playing: true, title: "S", denied: nil), "Spotify · Playing · S")
        CT.check("playing, no title", MusicFollow.statusLine(shown: .appleMusic, playing: true, title: nil, denied: nil), "Apple Music · Playing · Unknown")
        CT.check("paused", MusicFollow.statusLine(shown: .spotify, playing: false, title: "S", denied: nil), "Spotify · Paused")
        CT.check("nothing", MusicFollow.statusLine(shown: nil, playing: false, title: nil, denied: nil), "Not playing")
        CT.check("a refusal wins", MusicFollow.statusLine(shown: .spotify, playing: true, title: "S", denied: .spotify), "Spotify: automation not allowed")
        CT.check("second line", [MusicFollow.secondLine(artist: "Sam", app: .spotify), MusicFollow.secondLine(artist: nil, app: .appleMusic), MusicFollow.secondLine(artist: "Sam", app: nil), MusicFollow.secondLine(artist: nil, app: nil)], ["Sam · Spotify", "Apple Music", "Sam", nil])

        CT.section("a refusal shows only for the app it concerns")
        CT.check("the shown app refused", MusicFollow.deniedToShow(denied: [.spotify], shown: .spotify, lastDenied: .spotify), .spotify)
        CT.check("the other app refused: nothing", MusicFollow.deniedToShow(denied: [.spotify], shown: .appleMusic, lastDenied: .spotify), nil)
        CT.check("nothing shown: the last refusal", MusicFollow.deniedToShow(denied: [.appleMusic, .spotify], shown: nil, lastDenied: .appleMusic), .appleMusic)
        CT.check("a cleared refusal is not shown", MusicFollow.deniedToShow(denied: [], shown: nil, lastDenied: .spotify), nil)

        CT.section("a paused app whose process quits disappears (no timeout)")
        var p = MusicFollow()
        p.apply(.spotify, .paused, s)
        CT.check("paused shows", p.shown, .spotify)
        p.remove(.spotify)
        CT.check("after it quits: nothing shown", p.shown, nil)
        CT.check("and no track", p.shownTrack, nil)
        CT.checkTrue("and nothing plays", !p.isPlaying)

        CT.section("Open shows the shown app; with nothing shown, Apple Music as today")
        CT.check("Open: the shown app, else Apple Music", [MusicFollow.openApp(shown: .spotify), MusicFollow.openApp(shown: .appleMusic), MusicFollow.openApp(shown: nil)], [.spotify, .appleMusic, .appleMusic])

        CT.section("the Automation grant is recorded only for an app that was running before and after")
        CT.check("running before and after", MusicFollow.grantRecorded(runningBefore: true, runningAfter: true), true)
        CT.check("it quit during the script", MusicFollow.grantRecorded(runningBefore: true, runningAfter: false), false)
        CT.check("not running before", MusicFollow.grantRecorded(runningBefore: false, runningAfter: true), false)
        CT.check("not running at all", MusicFollow.grantRecorded(runningBefore: false, runningAfter: false), false)

        CT.section("a refusal is checked once, without a prompt: allowed clears it, denied or undetermined changes nothing")
        CT.check("noErr: allowed", MusicFollow.permissionAfterCheck(status: 0), true)
        CT.check("-1743: still denied", MusicFollow.permissionAfterCheck(status: -1743), false)
        CT.check("-1744: undetermined", MusicFollow.permissionAfterCheck(status: -1744), nil)
        CT.check("-600: another error", MusicFollow.permissionAfterCheck(status: -600), nil)
        CT.check("refused and running: checked", MusicFollow.shouldRecheck(denied: [.spotify, .appleMusic], running: [.spotify], pillOn: true), [.spotify])
        CT.check("refused but not running: never asked (it would launch)", MusicFollow.shouldRecheck(denied: [.spotify], running: [], pillOn: true), [])
        CT.check("pill off: nothing is checked", MusicFollow.shouldRecheck(denied: [.spotify], running: [.spotify], pillOn: false), [])
        CT.check("nothing refused: nothing", MusicFollow.shouldRecheck(denied: [], running: [.spotify], pillOn: true), [])

        CT.section("an old read or script result changes nothing")
        CT.check("the current generation, pill on: applied", MusicFollow.acceptsResult(resultGeneration: 3, currentGeneration: 3, pillOn: true), true)
        CT.check("an older generation: dropped", MusicFollow.acceptsResult(resultGeneration: 2, currentGeneration: 3, pillOn: true), false)
        CT.check("pill off: dropped", MusicFollow.acceptsResult(resultGeneration: 3, currentGeneration: 3, pillOn: false), false)
        CT.finish()
    }
}
