import Foundation

// The quick actions' pure state (F3a-mac, Task 8): where a quick action's text comes from (the message field, else the clipboard), the cap on a huge
// clipboard, the result card's states, the "latest run wins" gate and the one turn that answers under a quick action's own system text. Run from the
// repository root through scripts/test-companion-quick.sh.

@MainActor
@main
enum CompanionQuickStateTests {
    static func main() {
        CT.section("the text comes from the field when it has words, else from the clipboard")
        let plain = ["public.utf8-plain-text"]
        let concealed = ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"]
        CT.check("the field wins", CompanionQuickSource.pick(field: "my words", pasteboard: "copied", pasteboardTypes: plain)?.text, "my words")
        CT.check("the field's words are never labelled clipboard", CompanionQuickSource.pick(field: "my words", pasteboard: "copied", pasteboardTypes: plain)?.fromClipboard, false)
        CT.check("an empty field reads the clipboard", CompanionQuickSource.pick(field: "", pasteboard: "copied", pasteboardTypes: plain)?.text, "copied")
        CT.check("a clipboard text is labelled clipboard", CompanionQuickSource.pick(field: "", pasteboard: "copied", pasteboardTypes: plain)?.fromClipboard, true)
        CT.check("a field of spaces and line breaks reads the clipboard", CompanionQuickSource.pick(field: " \n\t ", pasteboard: "copied", pasteboardTypes: plain)?.text, "copied")
        CT.check("a clipboard with no text and an empty field is nothing", CompanionQuickSource.pick(field: "", pasteboard: nil, pasteboardTypes: plain)?.text, nil)
        CT.check("a clipboard of spaces is nothing", CompanionQuickSource.pick(field: "", pasteboard: "  \n ", pasteboardTypes: plain)?.text, nil)
        CT.check("the field is kept as typed (not trimmed here)", CompanionQuickSource.pick(field: "  a b ", pasteboard: nil, pasteboardTypes: [])?.text, "  a b ")
        CT.check("the field's text is not labelled", CompanionQuickSource.pick(field: "  a b ", pasteboard: nil, pasteboardTypes: [])?.fromClipboard, false)

        CT.section("a clipboard a password manager marked is never read (nspasteboard.org's three markers)")
        CT.check("the three markers, as their raw type names", CompanionQuickSource.skippedTypes, ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
        CT.check("a concealed clipboard is nothing when the field is empty", CompanionQuickSource.pick(field: "", pasteboard: "secret", pasteboardTypes: concealed)?.text, nil)
        CT.check("a transient clipboard is nothing", CompanionQuickSource.pick(field: "", pasteboard: "secret", pasteboardTypes: ["org.nspasteboard.TransientType"])?.text, nil)
        CT.check("an auto-generated clipboard is nothing", CompanionQuickSource.pick(field: "", pasteboard: "secret", pasteboardTypes: ["org.nspasteboard.AutoGeneratedType"])?.text, nil)
        CT.check("a skipped marker among other types still skips", CompanionQuickSource.pick(field: "", pasteboard: "secret", pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType", "public.html"])?.text, nil)
        CT.check("the field's words beat a concealed clipboard", CompanionQuickSource.pick(field: "my words", pasteboard: "secret", pasteboardTypes: concealed)?.text, "my words")
        CT.check("and the field's words are not labelled", CompanionQuickSource.pick(field: "my words", pasteboard: "secret", pasteboardTypes: concealed)?.fromClipboard, false)
        CT.check("a field of blanks and a concealed clipboard is nothing", CompanionQuickSource.pick(field: "  ", pasteboard: "secret", pasteboardTypes: concealed)?.text, nil)
        CT.check("the note for an unusable clipboard is the fixed sentence", CompanionQuickRules.noSelectionNote, "Select some text first.")
        CT.check("the card's clipboard line is the fixed sentence", CompanionQuickRules.clipboardNote, "From the clipboard.")

        CT.section("a huge clipboard is cut before it is worked on, and says so")
        let small = CompanionQuickSource.capped("hello")
        CT.check("a short text is as it is", small.text, "hello")
        CT.check("a short text is not cut", small.cut, false)
        let big = String(repeating: "a", count: CompanionQuickSource.capChars + 5_000)
        let cappedBig = CompanionQuickSource.capped(big)
        CT.check("a long text keeps its first capChars characters", cappedBig.text.count, CompanionQuickSource.capChars)
        CT.check("a long text says it was cut", cappedBig.cut, true)
        let edge = CompanionQuickSource.capped(String(repeating: "b", count: CompanionQuickSource.capChars))
        CT.check("a text of exactly capChars is whole", edge.cut, false)
        // multi-byte characters: the cap counts characters, so it cannot split one
        let wide = CompanionQuickSource.capped(String(repeating: "e\u{301}\u{1F431}", count: CompanionQuickSource.capChars))
        CT.checkTrue("a text of wide characters is cut on a character", wide.cut && wide.text.count == CompanionQuickSource.capChars && wide.text.unicodeScalars.count > wide.text.count)

        CT.section("the result card's states")
        let running = QuickResult.started(kind: "fix", cut: false, sourcePID: 321)
        CT.checkTrue("a started run is running, with no text and no note", running.running && running.text.isEmpty && running.note == nil)
        CT.check("it keeps the source app", running.sourcePID, 321)
        CT.check("a fix reads Fixed", running.title, "Fixed")
        CT.check("a run going reads Fixing…", running.heading, "Fixing…")
        CT.check("a rewrite going reads Rewriting…", QuickResult.started(kind: "rewrite", cut: false, sourcePID: nil).heading, "Rewriting…")
        CT.check("a result reads its title", running.finished(text: "x").heading, "Fixed")
        CT.check("a failed fix says so", running.failed("n").heading, "Couldn't fix that")
        CT.check("a failed rewrite says so", QuickResult.started(kind: "rewrite", cut: false, sourcePID: nil).failed("n").heading, "Couldn't rewrite that")
        CT.check("a rewrite reads Rewritten", QuickResult.started(kind: "rewrite", cut: false, sourcePID: nil).title, "Rewritten")
        let done = running.finished(text: "Fixed words.")
        CT.checkTrue("a finished run has its text and is not running", !done.running && done.text == "Fixed words." && done.note == nil)
        CT.check("a finished run keeps the kind and the source", [done.kind, "\(done.sourcePID ?? 0)"], ["fix", "321"])
        CT.checkTrue("a finished run with a source app offers Replace", done.canReplace)
        CT.checkTrue("a finished run with no source app does not", !QuickResult.started(kind: "fix", cut: false, sourcePID: nil).finished(text: "x").canReplace)
        CT.checkTrue("a run still going does not offer Replace", !running.canReplace)
        let cutDone = QuickResult.started(kind: "fix", cut: true, sourcePID: 321).finished(text: "x")
        CT.checkTrue("a result made from a cut text offers Copy only, never Replace", cutDone.canCopy && !cutDone.canReplace && cutDone.cut)
        CT.check("Services says what to do when nothing is selected", CompanionQuickRules.noSelectionNote, "Select some text first.")
        let empty = running.finished(text: "")
        CT.checkTrue("an empty reply is a failure with a fixed sentence, and offers nothing", !empty.running && empty.note == CompanionQuickRules.emptyNote && !empty.canReplace && !empty.canCopy)
        CT.check("a failure keeps the note it is given and no text", running.failed("Couldn't reach it.").note, "Couldn't reach it.")
        CT.checkTrue("a failed run stops running and offers nothing", !running.failed("x").running && !running.failed("x").canReplace && !running.failed("x").canCopy)
        CT.checkTrue("a finished run offers Copy", done.canCopy)
        var noted = done
        noted.note = CompanionChrome.replaceNote
        CT.checkTrue("a note after Replace keeps the text and the buttons", noted.canReplace && noted.canCopy && noted.text == "Fixed words.")
        CT.check("a cut text carries its flag", QuickResult.started(kind: "fix", cut: true, sourcePID: nil).cut, true)
        CT.check("a run is not from the clipboard unless it says so", running.fromClipboard, false)
        let fromClip = QuickResult.started(kind: "fix", cut: false, sourcePID: nil, fromClipboard: true)
        CT.checkTrue("a clipboard run keeps its label through its result and its failure", fromClip.fromClipboard && fromClip.finished(text: "x").fromClipboard && fromClip.failed("n").fromClipboard)
        CT.checkTrue("a clipboard run has no source app, so no Replace", !fromClip.finished(text: "x").canReplace)

        CT.section("the latest run wins")
        var gate = QuickGate()
        let first = gate.begin()
        CT.checkTrue("the first run is current", gate.isCurrent(first))
        let second = gate.begin()
        CT.checkTrue("a second run makes the first stale", !gate.isCurrent(first) && gate.isCurrent(second))
        gate.invalidate()
        CT.checkTrue("closing the card makes every run stale", !gate.isCurrent(second))

        CT.section("a quick Explain answers its first turn under its own system text, once, for its own question")
        let pending = QuickFirstTurn(system: "SYS", user: "<text>\nx\n</text>")
        CT.check("the first turn, the same question", pending.system(forQuery: "<text>\nx\n</text>", turnCount: 1), "SYS")
        CT.check("a different question is a normal turn", pending.system(forQuery: "and why?", turnCount: 1), nil)
        CT.check("once the first reply has landed it is a normal turn", pending.system(forQuery: "<text>\nx\n</text>", turnCount: 3), nil)
        CT.check("a tried-again first turn (the user turn taken back) still uses it", pending.system(forQuery: "<text>\nx\n</text>", turnCount: 0), "SYS")
        CT.check("two turns in is a normal turn", pending.system(forQuery: "<text>\nx\n</text>", turnCount: 2), nil)

        CT.section("the screenshot is read only when the clipboard's types offer an image and carry no skipped marker")
        CT.checkTrue("a PNG alone is an image to read", CompanionQuickSource.holdsReadableImage(["public.png"]))
        CT.checkTrue("a TIFF alone is an image to read", CompanionQuickSource.holdsReadableImage(["public.tiff"]))
        CT.checkTrue("an image beside text is read", CompanionQuickSource.holdsReadableImage(["public.utf8-plain-text", "public.png"]))
        CT.check("an image marked concealed is not read", CompanionQuickSource.holdsReadableImage(["public.png", "org.nspasteboard.ConcealedType"]), false)
        CT.check("a TIFF marked transient is not read", CompanionQuickSource.holdsReadableImage(["public.tiff", "org.nspasteboard.TransientType"]), false)
        CT.check("an image marked auto-generated is not read", CompanionQuickSource.holdsReadableImage(["public.png", "org.nspasteboard.AutoGeneratedType"]), false)
        CT.check("text alone is not an image", CompanionQuickSource.holdsReadableImage(["public.utf8-plain-text"]), false)
        CT.check("no types is not an image", CompanionQuickSource.holdsReadableImage([]), false)

        CT.section("a run that starts clears only the 'Select some text first.' note")
        CT.checkTrue("the selection note is the one a run clears", CompanionQuickRules.clearsNotice(CompanionQuickRules.noSelectionNote))
        CT.check("another note is kept", CompanionQuickRules.clearsNotice("Couldn't reach it."), false)
        CT.check("no note is nothing to clear", CompanionQuickRules.clearsNotice(nil), false)

        CT.finish()
    }
}
